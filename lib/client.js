		/**
		* Captions of the window menu bar the Desktop shell (Windows) draws itself
		* inside this page. The shell builds the bar in a preload script with its own
		* two-language table (English/Chinese) and re-labels it whenever the document
		* language changes, so a language pack has to rewrite these two labels in the
		* page. The menu items inside the popups are native Electron menus owned by the
		* shell process and cannot be reached from here.
		*/
		const SHELL_CAPTIONS = { application: "Приложение", edit: "Правка", menuBar: "Меню приложения" };
		/** Attribute the Desktop preload puts on its caption-menu host element. */
		const SHELL_MENU_MARKER = "[data-windows-menu]";
		/**
		* Rewrite the caption-bar labels, skipping writes that would change nothing
		* (an observer-driven rewrite of the same text would keep re-triggering itself).
		* @param root - the caption menu's shadow root.
		*/
		function patchShellCaptions(root) {
			const bar = root.querySelector('[role="menubar"]');
			if (bar !== null && bar.getAttribute("aria-label") !== SHELL_CAPTIONS.menuBar) bar.setAttribute("aria-label", SHELL_CAPTIONS.menuBar);
			const buttons = root.querySelectorAll('button[role="menuitem"]');
			const labels = [SHELL_CAPTIONS.application, SHELL_CAPTIONS.edit];
			for (let index = 0; index < labels.length && index < buttons.length; index += 1) {
				if (buttons[index].textContent !== labels[index]) buttons[index].textContent = labels[index];
			}
		}
		/**
		* Keep the desktop caption bar Russian while Russian is the active language.
		* Does nothing outside a browser or when the Desktop shell draws no such bar.
		* @param locale - the locale registry to follow.
		* @returns disposer that withdraws both observers and the subscription.
		*/
		function installShellCaptions(locale) {
			if (typeof document === "undefined" || typeof MutationObserver === "undefined") return () => {};
			let host;
			let bodyObserver;
			let menuObserver;
			const sync = () => {
				if (locale.getLocale().active !== LANGUAGE.id) return;
				const root = host?.shadowRoot;
				if (root) patchShellCaptions(root);
			};
			const attach = () => {
				const found = document.querySelector(SHELL_MENU_MARKER);
				if (found === null || found.shadowRoot === null) return false;
				if (found !== host) {
					if (menuObserver !== undefined) menuObserver.disconnect();
					host = found;
					menuObserver = new MutationObserver(sync);
					menuObserver.observe(found.shadowRoot, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-label"] });
				}
				sync();
				return true;
			};
			if (!attach()) {
				bodyObserver = new MutationObserver(() => {
					if (attach()) bodyObserver.disconnect();
				});
				bodyObserver.observe(document.body ?? document.documentElement, { childList: true, subtree: true });
			}
			const unsubscribe = locale.subscribe(sync);
			return () => {
				if (bodyObserver !== undefined) bodyObserver.disconnect();
				if (menuObserver !== undefined) menuObserver.disconnect();
				unsubscribe();
			};
		}
